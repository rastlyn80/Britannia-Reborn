"""Generate the runtime native-ID table from the reviewed category recipes."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def build():
 rows=json.loads((ROOT/'scripts/human-coverage-recipes.json').read_text())['assets']
 seen=set();lines=['extends RefCounted','## Generated by scripts/build-human-coverage-registry.py.','## Category coverage is separate from exact original item design fidelity.','const ITEMS := {']
 for row in rows:
  for graphic in row['graphics']:
   assert graphic not in seen,hex(graphic);seen.add(graphic)
   lines.append('\t0x%04x:["%s","coverage/%s"],'%(graphic,row['slot'],row['key']))
 lines+=['}','const STANCES := {']
 for row in rows:
  if 'stance' in row:lines.append('\t"coverage/%s":"%s",'%(row['key'],row['stance']))
 lines+=['}','']
 (ROOT/'Viewer/Presentation/HumanCoverageWardrobe.gd').write_text('\n'.join(lines))
 print('HUMAN CATEGORY REGISTRY:',len(rows),'assets,',len(seen),'native graphics')
if __name__=='__main__':build()
